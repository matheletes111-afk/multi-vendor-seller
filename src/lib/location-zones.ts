// Deduplicated array of all valid region names
export const ALL_LOCATION_REGIONS: string[] = Array.from(
  new Set(LOCATION_ZONES.flatMap((z) => z.regions))
)

// Specific zone names (ZONE 1 to ZONE 15)
export const SPECIFIC_ZONE_NAMES: string[] = LOCATION_ZONES
  .filter((z) => z.zone.startsWith("ZONE"))
  .map((z) => z.zone)

// All specific location regions in ZONE 1 - 15 sorted by length descending
export const SPECIFIC_LOCATION_REGIONS: string[] = Array.from(
  new Set(
    LOCATION_ZONES.filter((z) => z.zone.startsWith("ZONE")).flatMap((z) => z.regions)
  )
).sort((a, b) => b.length - a.length)

