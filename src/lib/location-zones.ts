// Map from region name (uppercase/trimmed) to Zone name
const REGION_TO_ZONE_MAP: Record<string, string> = {}
LOCATION_ZONES.forEach((z) => {
  z.regions.forEach((r) => {
    REGION_TO_ZONE_MAP[r.trim().toUpperCase()] = z.zone
  })
})

export function getZoneForRegion(regionName?: string | null): string {
  if (!regionName) return "Other"
  const clean = regionName.trim().toUpperCase()
  return REGION_TO_ZONE_MAP[clean] || "Other"
}
